//! An equality chain over one value prints as the `switch` it is (ROADMAP D474), and only where
//! every test is an equality of that value against a distinct proven constant.

use crate::common::{BASE, Literal};
use r2engine::program::OpenProgram;

fn c_of(code: &'static [u8]) -> String {
    let size = code.len() as u64;
    let mut program = OpenProgram::of(Literal::of_code(code, &[("f", BASE, size)]));
    program
        .rendered(BASE)
        .expect("it renders")
        .response
        .output
        .into_text()
}

/// `cmp edi, 1; je A; cmp edi, 2; je B; cmp edi, 3; je C; cmp edi, 4; je D; xor eax, eax; ret`,
/// then `A: mov eax, 10; ret`, `B: mov eax, 20; ret`, `C: mov eax, 30; ret`, `D: mov eax, 40; ret`.
const FOUR_CASES: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x12, 0x83, 0xff, 0x02, 0x74, 0x13, 0x83, 0xff, 0x03, 0x74, 0x14, 0x83,
    0xff, 0x04, 0x74, 0x15, 0x31, 0xc0, 0xc3, 0xb8, 0x0a, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x14, 0x00,
    0x00, 0x00, 0xc3, 0xb8, 0x1e, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x28, 0x00, 0x00, 0x00, 0xc3,
];

#[test]
fn four_equality_tests_of_one_register_print_as_a_switch() {
    let c = c_of(FOUR_CASES);
    assert_eq!(c.matches("switch (").count(), 1, "{c}");
    for value in 1..=4 {
        assert_eq!(c.matches(&format!("case {value}U:")).count(), 1, "{c}");
    }
    assert!(c.contains("default:"), "{c}");
    assert!(!c.contains("if ("), "{c}");
}

/// The same four arms, with `add edi, 1` before the third test: two tests read one value and two
/// another, so no three compare one value.
const REDEFINED: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x15, 0x83, 0xff, 0x02, 0x74, 0x16, 0x83, 0xc7, 0x01, 0x83, 0xff, 0x03,
    0x74, 0x14, 0x83, 0xff, 0x04, 0x74, 0x15, 0x31, 0xc0, 0xc3, 0xb8, 0x0a, 0x00, 0x00, 0x00, 0xc3,
    0xb8, 0x14, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x1e, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x28, 0x00, 0x00,
    0x00, 0xc3,
];

/// Tests of 1, 2 and 1 again: a repeated value is no case of its own.
const REPEATED: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x0d, 0x83, 0xff, 0x02, 0x74, 0x0e, 0x83, 0xff, 0x01, 0x74, 0x0f, 0x31,
    0xc0, 0xc3, 0xb8, 0x0a, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x14, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x1e,
    0x00, 0x00, 0x00, 0xc3,
];

/// Two tests, of 1 and 2.
const TWO_CASES: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x08, 0x83, 0xff, 0x02, 0x74, 0x09, 0x31, 0xc0, 0xc3, 0xb8, 0x0a, 0x00,
    0x00, 0x00, 0xc3, 0xb8, 0x14, 0x00, 0x00, 0x00, 0xc3,
];

/// `L: cmp edi, 1; je A; cmp edi, 2; je B; cmp edi, 3; je OUT; dec edi; jmp L`, the arms jumping
/// back to `L`, `OUT: add eax, edi; ret`: the third arm's `break` leaves the loop.
const BREAKS_THE_LOOP: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x0e, 0x83, 0xff, 0x02, 0x74, 0x0f, 0x83, 0xff, 0x03, 0x74, 0x11, 0xff,
    0xcf, 0xeb, 0xed, 0xff, 0xc0, 0xff, 0xcf, 0xeb, 0xe7, 0x83, 0xc0, 0x02, 0xff, 0xcf, 0xeb, 0xe0,
    0x01, 0xf8, 0xc3,
];

/// Tests of `== 1`, `< 5` and `== 3`: an ordered test is no case.
const ORDERED: &[u8] = &[
    0x83, 0xff, 0x01, 0x74, 0x0d, 0x83, 0xff, 0x05, 0x7c, 0x0e, 0x83, 0xff, 0x03, 0x74, 0x0f, 0x31,
    0xc0, 0xc3, 0xb8, 0x0a, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x14, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x1e,
    0x00, 0x00, 0x00, 0xc3,
];

#[test]
fn a_chain_that_fails_a_condition_stays_an_if_chain() {
    for (name, code, tests) in [
        ("redefined", REDEFINED, 4),
        ("repeated", REPEATED, 3),
        ("two cases", TWO_CASES, 2),
        ("breaks the loop", BREAKS_THE_LOOP, 3),
        ("ordered", ORDERED, 3),
    ] {
        let c = c_of(code);
        assert!(!c.contains("switch ("), "{name}: {c}");
        assert!(c.matches("if (").count() >= tests, "{name}: {c}");
    }
}

/// `cmp dil, 0x80; je A; cmp dil, 0x10; je B; cmp dil, 0x7f; je C; xor eax, eax; ret` and three
/// returns: the cases are the byte's own values, each one a `uint8_t` holds.
const BYTE_CASES: &[u8] = &[
    0x40, 0x80, 0xff, 0x80, 0x74, 0x0f, 0x40, 0x80, 0xff, 0x10, 0x74, 0x0f, 0x40, 0x80, 0xff, 0x7f,
    0x74, 0x0f, 0x31, 0xc0, 0xc3, 0xb8, 0x0a, 0x00, 0x00, 0x00, 0xc3, 0xb8, 0x14, 0x00, 0x00, 0x00,
    0xc3, 0xb8, 0x1e, 0x00, 0x00, 0x00, 0xc3,
];

#[test]
fn a_byte_switch_names_each_case_as_the_byte_holds_it() {
    let c = c_of(BYTE_CASES);
    assert_eq!(c.matches("switch (").count(), 1, "{c}");
    for value in ["128U", "16U", "127U"] {
        assert_eq!(c.matches(&format!("case {value}:")).count(), 1, "{c}");
    }
}

/// 0pack 0x673f25's dispatch (D648): `sub dil, 0x73; js default` clears the byte's top bit, so the
/// `movzx` index reads 128 entries; the words past them belong to no arm of this table.
fn sign_bounded_dispatch() -> &'static [u8] {
    let mut code = vec![
        0x40, 0x80, 0xef, 0x73, // 1000 sub dil, 0x73
        0x78, 0x20, // 1004 js 0x1026
        0x48, 0x8d, 0x0d, 0x23, 0x00, 0x00, 0x00, // 1006 lea rcx, [0x1030]
        0x40, 0x0f, 0xb6, 0xff, // 100d movzx edi, dil
        0x48, 0x63, 0x04, 0xb9, // 1011 movsxd rax, dword [rcx + rdi*4]
        0x48, 0x01, 0xc8, 0xff, 0xe0, // 1015 add rax, rcx; jmp rax
        0xb8, 0x01, 0x00, 0x00, 0x00, 0xc3, // 101a even arms: mov eax, 1; ret
        0xb8, 0x02, 0x00, 0x00, 0x00, 0xc3, // 1020 odd arms: mov eax, 2; ret
        0x31, 0xc0, 0xc3, // 1026 default: xor eax, eax; ret
        0x90, 0x90, 0x90, 0x90, 0x90, 0x90, 0x90, // 1029 padding
    ];
    for arm in 0..128 {
        let offset: i32 = if arm % 2 == 0 { -0x16 } else { -0x10 };
        code.extend_from_slice(&offset.to_le_bytes());
    }
    // Another table's words follow, as at 0x7604c0: entry 128 would send control into this one.
    code.extend_from_slice(&[0u8; 512]);
    Box::leak(code.into_boxed_slice())
}

#[test]
fn a_sign_test_on_a_byte_bounds_its_zero_extended_index() {
    let code = sign_bounded_dispatch();
    let size = 0x30;
    let mut program = OpenProgram::of(Literal::of_code(code, &[("f", BASE, size)]));
    let c = (program.rendered(BASE).expect("it renders"))
        .response
        .output
        .into_text();
    assert_eq!(c.matches("switch (").count(), 1, "{c}");
    assert_eq!(c.matches("case ").count(), 128, "{c}");
    assert!(!c.contains("case 128:") && !c.contains("case 128U:"), "{c}");
}
