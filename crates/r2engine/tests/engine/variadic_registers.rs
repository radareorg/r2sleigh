//! The count-driven tail with the cursors in registers, and on AArch64 (ROADMAP SM, W14): shapes.c's
//! `vfold` as gcc and clang emitted it, and the edits that make its count bound nothing.

use crate::common;

use common::{BASE, GLIBC, Literal};
use r2engine::program::OpenProgram;

#[derive(Clone, Copy)]
enum Target {
    X86,
    Aarch64,
}

/// Where the image holds what follows `vfold`: `halt`, where the stack protector's call lands;
/// `two(a, b)`, which calls `vfold(2, a, b)`; and `dynamic(n)`, which calls `vfold(n, 5)`.
const HALT: usize = 0x200;
const TWO: usize = 0x220;
const DYNAMIC: usize = 0x260;

/// `vfold` at `BASE`, then the rest of the image.
fn image(vfold: &[u8], target: Target) -> &'static [u8] {
    let mut code = vfold.to_vec();
    assert!(code.len() <= HALT, "vfold overlaps the image");
    code.resize(HALT, 0xcc);
    match target {
        Target::X86 => {
            let call = |at: usize| -> Vec<u8> {
                let rel = -i32::try_from(at + 5).expect("an offset");
                [&[0xe8][..], &rel.to_le_bytes()].concat()
            };
            code.extend([0xeb, 0xfe]); // jmp halt
            code.resize(TWO, 0xcc);
            code.extend([0x48, 0x89, 0xf2]); // movq %rsi, %rdx
            code.extend([0x48, 0x89, 0xfe]); // movq %rdi, %rsi
            code.extend([0xbf, 0x02, 0x00, 0x00, 0x00]); // movl $0x2, %edi
            code.extend([0x31, 0xc0]); // xorl %eax, %eax
            code.extend(call(TWO + 0xd)); // callq vfold
            code.push(0xc3); // retq
            code.resize(DYNAMIC, 0xcc);
            code.extend([0xbe, 0x05, 0x00, 0x00, 0x00]); // movl $0x5, %esi
            code.extend([0x31, 0xc0]); // xorl %eax, %eax
            code.extend(call(DYNAMIC + 7)); // callq vfold
            code.push(0xc3); // retq
        }
        Target::Aarch64 => {
            let bl = |at: usize| -> [u8; 4] {
                let words = -i32::try_from(at / 4).expect("an offset");
                (0x9400_0000 | (words.cast_unsigned() & 0x03ff_ffff)).to_le_bytes()
            };
            code.extend([0x00, 0x00, 0x00, 0x14]); // b halt
            code.resize(TWO, 0xcc);
            code.extend([0xfd, 0x7b, 0xbf, 0xa9]); // stp x29, x30, [sp, #-16]!
            code.extend([0xe2, 0x03, 0x01, 0xaa]); // mov x2, x1
            code.extend([0xe1, 0x03, 0x00, 0xaa]); // mov x1, x0
            code.extend([0x40, 0x00, 0x80, 0x52]); // mov w0, #2
            code.extend(bl(TWO + 0x10)); // bl vfold
            code.extend([0xfd, 0x7b, 0xc1, 0xa8]); // ldp x29, x30, [sp], #16
            code.extend([0xc0, 0x03, 0x5f, 0xd6]); // ret
            code.resize(DYNAMIC, 0xcc);
            code.extend([0xfd, 0x7b, 0xbf, 0xa9]); // stp x29, x30, [sp, #-16]!
            code.extend([0xa1, 0x00, 0x80, 0xd2]); // mov x1, #5
            code.extend(bl(DYNAMIC + 8)); // bl vfold
            code.extend([0xfd, 0x7b, 0xc1, 0xa8]); // ldp x29, x30, [sp], #16
            code.extend([0xc0, 0x03, 0x5f, 0xd6]); // ret
        }
    }
    Vec::leak(code)
}

fn program(vfold: &[u8], target: Target) -> OpenProgram<Literal> {
    program_over(image(vfold, target), vfold.len(), target)
}

fn program_over(code: &'static [u8], vfold: usize, target: Target) -> OpenProgram<Literal> {
    let (two, dynamic) = match target {
        Target::X86 => (0x13, 0xd),
        Target::Aarch64 => (0x1c, 0x14),
    };
    let functions = [
        ("vfold", BASE, vfold as u64),
        ("halt", BASE + HALT as u64, 0x4),
        ("two", BASE + TWO as u64, two),
        ("dynamic", BASE + DYNAMIC as u64, dynamic),
    ];
    let literal = Literal::of_code(code, &functions).running_on(GLIBC);
    OpenProgram::of(match target {
        Target::X86 => literal,
        Target::Aarch64 => literal.in_aarch64(),
    })
}

/// `vfold` with `now` where it had `was`: an edit that keeps every other byte where it was.
fn edited(vfold: &[u8], at: usize, was: &[u8], now: &[u8]) -> Vec<u8> {
    assert_eq!(&vfold[at..at + was.len()], was, "vfold differs at {at:#x}");
    assert_eq!(was.len(), now.len());
    let mut code = vfold.to_vec();
    code[at..at + now.len()].copy_from_slice(now);
    code
}

/// `vfold` with the `len` bytes at `at` moved after its end, then `extra`, then a jump back: code
/// added without moving a byte. The moved instructions must hold no address of their own place.
fn spliced(vfold: &[u8], target: Target, (at, len): (usize, usize), extra: &[Piece]) -> Vec<u8> {
    let mut code = vfold.to_vec();
    let tramp = code.len();
    let moved = vfold[at..at + len].to_vec();
    match target {
        Target::X86 => {
            code[at] = 0xeb;
            code[at + 1] = u8::try_from(tramp - (at + 2)).expect("a short jump");
            code[at + 2..at + len].fill(0x90);
            code.extend(moved);
            for piece in extra {
                piece.emit_x86(&mut code);
            }
            let rel = i32::try_from(at as i64 + len as i64 - (code.len() as i64 + 5)).expect("a");
            code.extend([&[0xe9][..], &rel.to_le_bytes()].concat());
        }
        Target::Aarch64 => {
            assert_eq!(len, 4);
            code[at..at + 4].copy_from_slice(&jump_a64(at, tramp));
            code.extend(moved);
            for piece in extra {
                piece.emit_a64(&mut code);
            }
            let back = jump_a64(code.len(), at + 4);
            code.extend(back);
        }
    }
    code
}

fn jump_a64(from: usize, to: usize) -> [u8; 4] {
    let words = (to as i64 - from as i64) / 4;
    (0x1400_0000 | (words as u32 & 0x03ff_ffff)).to_le_bytes()
}

/// What a trampoline holds beyond the instruction it replaced.
enum Piece {
    /// Instruction bytes with no address in them.
    Code(&'static [u8]),
    /// A conditional branch to `vfold`'s offset: `je` on x86-64, `cbz` of the register on AArch64.
    LeaveIfZero(usize, u8),
}

impl Piece {
    fn emit_x86(&self, code: &mut Vec<u8>) {
        match self {
            Self::Code(bytes) => code.extend(*bytes),
            Self::LeaveIfZero(to, _) => {
                let rel = i32::try_from(*to as i64 - (code.len() as i64 + 6)).expect("a distance");
                code.extend([&[0x0f, 0x84][..], &rel.to_le_bytes()].concat());
            }
        }
    }

    fn emit_a64(&self, code: &mut Vec<u8>) {
        match self {
            Self::Code(bytes) => code.extend(*bytes),
            Self::LeaveIfZero(to, register) => {
                let words = (*to as i64 - code.len() as i64) / 4;
                let word = 0xb400_0000 | ((words as u32 & 0x7ffff) << 5) | u32::from(*register);
                code.extend(word.to_le_bytes());
            }
        }
    }
}

fn rendered(open: &mut OpenProgram<Literal>, at: u64) -> String {
    open.rendered(at)
        .expect("it renders")
        .response
        .output
        .into_text()
}

/// A body whose count bounds its tail passes exactly that many arguments, and a call whose count
/// no constant fixes stays the counted residual.
fn bounds_the_tail(vfold: &[u8], target: Target) {
    let mut open = program(vfold, target);
    let callee = rendered(&mut open, BASE);
    assert!(callee.contains("vfold(uint32_t arg0, ...)"), "{callee}");
    let two = rendered(&mut open, BASE + TWO as u64);
    assert!(two.contains("two(uint64_t arg0, uint64_t arg1)"), "{two}");
    assert!(two.contains("vfold(2, arg0, arg1)"), "{two}");
    assert!(!two.contains("argument count unproven"), "{two}");
    let dynamic = rendered(&mut open, BASE + DYNAMIC as u64);
    assert!(
        dynamic.contains(
            "call to vfold: variadic, its argument count unproven (count_argument_not_constant)"
        ),
        "{dynamic}"
    );
}

/// `two` over an edited `vfold` that is still variadic: the call stays the counted residual, never
/// `vfold(2, ...)`.
fn leaves_the_tail_unproven(vfold: &[u8], target: Target) {
    let mut open = program(vfold, target);
    let callee = rendered(&mut open, BASE);
    assert!(callee.contains("vfold(uint32_t arg0, ...)"), "{callee}");
    let two = rendered(&mut open, BASE + TWO as u64);
    assert!(two.contains("argument count unproven"), "{two}");
    assert!(!two.contains("vfold(2, arg0"), "{two}");
}

