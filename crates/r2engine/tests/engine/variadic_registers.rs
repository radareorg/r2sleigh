/// `vfold(1u, ...)` is called with the count a register holds, not a constant.
fn leaves_the_count_unproven_when_the_caller_rewrites_it(vfold: &[u8], target: Target) {
    let mut code = image(vfold, target).to_vec();
    let (at, was, now): (usize, &[u8], &[u8]) = match target {
        Target::X86 => (
            TWO + 6,
            &[0xbf, 0x02, 0, 0, 0],
            &[0x89, 0xf7, 0x90, 0x90, 0x90],
        ),
        Target::Aarch64 => (
            TWO + 12,
            &[0x40, 0x00, 0x80, 0x52],
            &[0xe0, 0x03, 0x01, 0x2a],
        ),
    };
    assert_eq!(&code[at..at + was.len()], was, "the caller differs");
    code[at..at + now.len()].copy_from_slice(now);
    let mut open = program_over(Vec::leak(code), vfold.len(), target);
    let two = rendered(&mut open, BASE + TWO as u64);
    assert!(two.contains("count_argument_not_constant"), "{two}");
    assert!(!two.contains("vfold(2,"), "{two}");
}

#[test]
fn a_count_register_rewritten_before_the_call_is_no_constant_on_every_register_cursor_build() {
    for (vfold, target) in [
        (GCC_O1, Target::X86),
        (CLANG_O1, Target::X86),
        (A64_GCC_O1, Target::Aarch64),
        (A64_CLANG_O1, Target::Aarch64),
    ] {
        bounds_the_tail(vfold, target);
        leaves_the_count_unproven_when_the_caller_rewrites_it(vfold, target);
    }
}

