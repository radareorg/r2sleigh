fn sysv() -> OpenProgram<Literal> {
    OpenProgram::of(Literal::of_code(
        SYSV,
        &[
            ("vf", BASE, 0x5b),
            ("take", BASE + 0x5b, 0x0c),
            ("caller", BASE + 0x70, 0x12),
            ("six", BASE + 0x90, 0x37),
            ("sum6", BASE + 0xc7, 0x1e),
            ("caller6", BASE + 0xf0, 0x26),
            ("arr", BASE + 0x120, 0x2d),
            ("sum5", BASE + 0x14d, 0x18),
            ("caller_arr", BASE + 0x170, 0x26),
            ("wrapper", BASE + 0x1a0, 0x2b),
            ("outer", BASE + 0x1d0, 0x10),
        ],
    ))
}

fn rendered(open: &mut OpenProgram<Literal>, at: u64) -> String {
    open.rendered(at)
        .expect("it renders")
        .response
        .output
        .into_text()
}

/// `vf` takes one fixed argument and a tail: its call is the counted variadic residual, never
/// `vf(1, 5, ...)` with four slots `caller` never wrote.
#[test]
fn a_register_save_area_is_a_variadic_tail_not_six_parameters() {
    let mut open = sysv();
    let callee = rendered(&mut open, BASE);
    assert!(callee.contains("vf(uint32_t arg0, ...)"), "{callee}");
    assert!(!callee.contains("arg1"), "{callee}");
    let caller = rendered(&mut open, BASE + 0x70);
    assert!(
        caller.contains("call to vf: variadic, its argument count unproven"),
        "{caller}"
    );
    assert!(!caller.contains("vf(1"), "{caller}");
    assert!(
        !caller.contains("argument slots read with no parameter"),
        "{caller}"
    );
    assert!(callee.contains("variadic tail registers"), "{callee}");
}

/// `wrapper` sets `al` for its call to `vf`, so even resolved before `vf` is read, the registers it
/// writes there are no count: `outer`'s call agrees with `wrapper`'s own floor under `aa`.
#[test]
fn a_call_handed_a_vector_count_counts_no_argument_from_registers() {
    let mut open = sysv();
    open.analyse_program().expect("it surveys");
    let outer = rendered(&mut open, BASE + 0x1d0);
    assert!(
        outer.contains("call to wrapper: its arity is only at least 0 (a floor)"),
        "{outer}"
    );
    assert!(!outer.contains("wrapper(3"), "{outer}");
    let wrapper = rendered(&mut open, BASE + 0x1a0);
    assert!(!wrapper.contains("arg0"), "{wrapper}");
}

/// `six` spills all six in order and stores the spill's address: no named slot sits below the run.
#[test]
fn an_o0_body_spilling_its_six_parameters_stays_exact() {
    let mut open = sysv();
    let callee = rendered(&mut open, BASE + 0x90);
    assert!(callee.contains("uint64_t arg5)"), "{callee}");
    let caller = rendered(&mut open, BASE + 0xf0);
    assert!(caller.contains("six(1, 2, 3, 4, 5, 6)"), "{caller}");
}

/// `arr` lays `rsi`..`r9` out as a save area whose address it hands `sum5` in a register, unstored.
