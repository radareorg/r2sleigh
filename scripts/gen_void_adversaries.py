"""Generate the void-soundness adversaries (tests/gold/void_soundness/).

A function the engine renders `void` because no call reads its result is a claim of absence, and
it is only as good as the reads the engine can see. Each program here has one value type and, for
it, producers that return it by every route the engine must follow (computed, forwarded through a
function pointer, chained through a function of the image) and consumers that read it in every way
a caller can: stored, printed, handed to another call, read in one lane or half, taken by an
instruction the lift states no register for. The manifest names, for every function, whether
some caller reads its result; scripts/void_soundness.py compiles the programs and fails if a
function the source declares with a value, and a caller reads, is rendered `void`.

    gen_void_adversaries.py            write the programs and manifest.json
    gen_void_adversaries.py --check    fail if they are not what this script writes
"""

